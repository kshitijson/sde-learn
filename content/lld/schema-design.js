<p><strong>Third normal form</strong>: non-key columns depend on the key and nothing else ("the key, the whole key, and nothing but the key"). In <code>orders</code>, <code>cust_phone</code> depends on the customer, and <code>rest_city</code> depends on the restaurant, not on the order. That is a <strong>transitive dependency</strong>: order → restaurant → city. Pull customers and restaurants into their own tables and point at them by id.</p>
